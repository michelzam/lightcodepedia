-- Where to run it: your project's dashboard → SQL Editor → new query → paste all of this → Run.
-- Once per project; safe to run again (updates in place). The author's device offers this
-- file under a grid (📋 Copy the setup SQL) when the door is missing or older than the engine.
-- A class creates its own table (on the author's device), the class shares it by an
-- unlisted name. Tables live in a private schema "lc": no rule opens them, nobody reads
-- them directly; the lc_* functions are the only door. (Michel, 2026-10-17; live 2026-10-20)

create schema if not exists lc;
revoke all on schema lc from public, anon, authenticated;

create table if not exists lc.authors (token_hash text primary key, at timestamptz not null default now());
-- one unlisted name for the whole database (Michel, 2026-10-17: "1: db")
create table if not exists lc.space   (one boolean primary key default true check (one), secret text not null);
alter table lc.authors enable row level security;
alter table lc.space   enable row level security;

create or replace function lc.hash(token text) returns text language sql immutable as
$$ select encode(sha256(convert_to(coalesce(token, ''), 'UTF8')), 'hex') $$;

create or replace function lc.is_author(token text) returns boolean language sql stable as
$$ select exists (select 1 from lc.authors where token_hash = lc.hash(token)) $$;

create or replace function lc.check_name(n text) returns text language plpgsql immutable as $$
begin
  if n is null or n !~ '^[a-z][a-z0-9_]{0,40}$' then
    raise exception 'lc: "%" is not a table or column name (lowercase letters, digits, _)', n;
  end if;
  return n;
end $$;

-- the table's own notes on every line: when, how, from where (never shown to the class)
create or replace function lc.stamp() returns trigger language plpgsql as $$
declare h json := coalesce(nullif(current_setting('request.headers', true), '')::json, '{}'::json);
begin
  new._changed_at := now();
  new._change     := lower(tg_op);
  new._ip         := nullif(trim(split_part(coalesce(h->>'x-forwarded-for', h->>'x-real-ip', ''), ',', 1)), '');
  new._country    := h->>'cf-ipcountry';
  new._browser    := h->>'user-agent';
  return new;
end $$;

-- LIVE TABLES (Michel, 2026-10-20): after every change a table says so on the platform's
-- broadcast, on a topic named by the database's unlisted name — the name is the secret, as
-- for reads and writes. Always on and cheap (one call per write); a page listens only when
-- its database line says live="true". A project without realtime.send() skips it quietly.
create or replace function lc.live() returns trigger language plpgsql security definer set search_path = '' as $$
declare s text; r jsonb;
begin
  select secret into s from lc.space;
  if s is null then return coalesce(new, old); end if;
  r := case when tg_op = 'DELETE' then jsonb_build_object('id', old.id)
            else to_jsonb(new) - '_ip' - '_country' - '_browser' end;
  begin
    perform realtime.send(jsonb_build_object('table', tg_table_name, 'op', lower(tg_op), 'id', coalesce(new.id, old.id), 'row', r),
                          'change', 'lc-' || s, false);
  exception when undefined_function or invalid_schema_name then null;
  end;
  return coalesce(new, old);
end $$;

-- 0 · which setup this project holds — the engine compares, the author's device is told
create or replace function public.lc_version() returns int language sql immutable as $$ select 2 $$;

-- 1 · the first device to claim becomes the author (delete from lc.authors to start over)
create or replace function public.lc_claim(token text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if length(coalesce(token, '')) < 24 then raise exception 'lc: an author key is at least 24 characters'; end if;
  if not exists (select 1 from lc.authors) then
    insert into lc.authors (token_hash) values (lc.hash(token));
  end if;
  return lc.is_author(token);
end $$;

-- 2 · the author's class makes its table, or adds the columns it gained; returns the database's unlisted name
create or replace function public.lc_ensure(token text, tbl text, cols jsonb) returns text
language plpgsql security definer set search_path = '' as $$
declare c record; typ text; s text; cur text;
begin
  if not lc.is_author(token) then raise exception 'lc: only the author makes tables'; end if;
  perform lc.check_name(tbl);
  execute format('create table if not exists lc.%I (id bigint generated by default as identity primary key)', tbl);
  execute format('alter table lc.%I enable row level security', tbl);
  -- cols: the class's attributes in order, [{"n": "dog", "t": "str", "was": "old_name"}, …]
  for c in select e->>'n' as n, e->>'t' as t, e->>'was' as was
             from jsonb_array_elements(case when jsonb_typeof(cols) = 'array' then cols else '[]'::jsonb end)
                  with ordinality as x(e, i) order by i loop
    -- _sub: which subclass a row is (Michel, 2026-10-17: "rows are twice — a _subname")
    if c.n = '_sub' then
      execute format('alter table lc.%I add column if not exists _sub text', tbl);
      continue;
    end if;
    perform lc.check_name(c.n);
    if c.n = 'id' then continue; end if;
    -- was="old": an attribute renamed keeps its column and its data
    if c.was is not null and c.was <> c.n and c.was <> 'id' and left(c.was, 1) <> '_'
       and exists (select 1 from pg_attribute where attrelid = format('lc.%I', tbl)::regclass
                   and attname = lc.check_name(c.was) and not attisdropped)
       and not exists (select 1 from pg_attribute where attrelid = format('lc.%I', tbl)::regclass
                       and attname = c.n and not attisdropped) then
      execute format('alter table lc.%I rename column %I to %I', tbl, c.was, c.n);
    end if;
    typ := case c.t when 'int' then 'bigint' when 'float' then 'double precision'
                    when 'bool' then 'boolean' else 'text' end;
    execute format('alter table lc.%I add column if not exists %I %s', tbl, c.n, typ);
    -- a type changed in the class (Michel, 2026-10-18: laps was str a second,
    -- then int): the column follows; a blank becomes null, a value that does
    -- not convert stops it and says which
    select format_type(atttypid, atttypmod) into cur from pg_attribute
     where attrelid = format('lc.%I', tbl)::regclass and attname = c.n and not attisdropped;
    if cur is distinct from typ then
      begin
        execute format('alter table lc.%I alter column %I type %s using nullif(trim(%I::text), '''')::%s',
                       tbl, c.n, typ, c.n, typ);
      exception when others then
        raise exception 'lc: % holds a value that is not %, fix it in the grid, then ↻', c.n, c.t;
      end;
    end if;
  end loop;
  -- the stamp columns, after the class's (on a new table)
  execute format('alter table lc.%I add column if not exists _changed_at timestamptz not null default now(),
      add column if not exists _change text not null default ''insert'',
      add column if not exists _ip text, add column if not exists _country text,
      add column if not exists _browser text', tbl);
  execute format('create or replace trigger lc_stamp before insert or update on lc.%I
      for each row execute function lc.stamp()', tbl);
  execute format('create or replace trigger lc_live after insert or update or delete on lc.%I
      for each row execute function lc.live()', tbl);
  insert into lc.space (secret) values (substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
    on conflict on constraint space_pkey do nothing;
  select secret into s from lc.space;
  return s;
end $$;

-- 2b · the author drops the columns no attribute uses any more (🧹, after confirming)
create or replace function public.lc_drop(token text, tbl text, cols jsonb) returns int
language plpgsql security definer set search_path = '' as $$
declare c text; n int := 0;
begin
  if not lc.is_author(token) then raise exception 'lc: only the author changes tables'; end if;
  perform lc.check_name(tbl);
  for c in select jsonb_array_elements_text(case when jsonb_typeof(cols) = 'array' then cols else '[]'::jsonb end) loop
    if c = 'id' or left(c, 1) = '_' then continue; end if;   -- the id and the stamps stay
    perform lc.check_name(c);
    execute format('alter table lc.%I drop column if exists %I', tbl, c);
    n := n + 1;
  end loop;
  return n;
end $$;

create or replace function lc.open(share text, tbl text) returns void
language plpgsql stable set search_path = '' as $$
begin
  perform lc.check_name(tbl);
  if to_regclass(format('lc.%I', tbl)) is null
     or not exists (select 1 from lc.space where space.secret = share) then
    raise exception 'lc: no list by that name';
  end if;
end $$;

-- 3 · read: the rows, without where they came from
create or replace function public.lc_read(share text, tbl text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare out jsonb;
begin
  perform lc.open(share, tbl);
  execute format('select coalesce(jsonb_agg(to_jsonb(t) - ''_ip'' - ''_country'' - ''_browser'' order by t.id), ''[]'')
                  from lc.%I t', tbl) into out;
  return out;
end $$;

-- 4 · save: new rows, changed rows (only the keys sent), gone rows — in one go
create or replace function public.lc_save(share text, tbl text, ins jsonb, upd jsonb, del jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare cols text; sets text; r jsonb; n_ins int := 0; n_upd int := 0; n_del int := 0; k int;
begin
  perform lc.open(share, tbl);
  select string_agg(quote_ident(attname), ', ' order by attnum),
         string_agg(format('%1$I = case when $1 ? %2$L then r.%1$I else t.%1$I end', attname, attname), ', ' order by attnum)
    into cols, sets
    from pg_attribute
   where attrelid = format('lc.%I', tbl)::regclass and attnum > 0 and not attisdropped
     and attname <> 'id' and (left(attname, 1) <> '_' or attname = '_sub');
  if cols is null then return jsonb_build_object('ins', 0, 'upd', 0, 'del', 0); end if;
  if jsonb_typeof(ins) = 'array' and jsonb_array_length(ins) > 0 then
    execute format('insert into lc.%I (%s) select %s from jsonb_populate_recordset(null::lc.%I, $1)', tbl, cols, cols, tbl) using ins;
    n_ins := jsonb_array_length(ins);
  end if;
  if jsonb_typeof(upd) = 'array' then
    for r in select * from jsonb_array_elements(upd) loop
      execute format('update lc.%I t set %s from jsonb_populate_record(null::lc.%I, $1) r where t.id = ($1->>''id'')::bigint', tbl, sets, tbl) using r;
      get diagnostics k = row_count; n_upd := n_upd + k;
    end loop;
  end if;
  if jsonb_typeof(del) = 'array' and jsonb_array_length(del) > 0 then
    execute format('delete from lc.%I where id in (select (jsonb_array_elements_text($1))::bigint)', tbl) using del;
    get diagnostics n_del = row_count;
  end if;
  return jsonb_build_object('ins', n_ins, 'upd', n_upd, 'del', n_del);
end $$;

revoke all on function public.lc_version(), public.lc_claim(text), public.lc_ensure(text, text, jsonb), public.lc_drop(text, text, jsonb),
  public.lc_read(text, text), public.lc_save(text, text, jsonb, jsonb, jsonb) from public;
grant execute on function public.lc_version(), public.lc_claim(text), public.lc_ensure(text, text, jsonb), public.lc_drop(text, text, jsonb),
  public.lc_read(text, text), public.lc_save(text, text, jsonb, jsonb, jsonb) to anon, authenticated;
-- the tables already standing get the live trigger now (new ones get it from lc_ensure)
do $$ declare t record; begin
  for t in select tablename from pg_tables where schemaname = 'lc' and tablename not in ('authors', 'space') loop
    execute format('create or replace trigger lc_live after insert or update or delete on lc.%I
        for each row execute function lc.live()', t.tablename);
  end loop;
end $$;

notify pgrst, 'reload schema';
